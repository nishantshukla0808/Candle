'use client';

import Link from 'next/link';
import { useState } from 'react';
import type { JSX } from 'react';
import { ChartQuestion, type ChartQuestionView, type ChartReveal } from '../chart-question';
import { DuelsDisclaimer } from '../disclaimer';

/**
 * CHART_CHOICE format test page (docs/08 §3.4, Phase 8 Stage 1).
 *
 * This is NOT a duel — it is the format preview for the CHART_CHOICE
 * renderer, so the Chart Detective duel (Stage 2) can be built on a
 * renderer that already works. It shows one real seed item (qb-571)
 * through the `ChartQuestion` component, with buttons to simulate the
 * reveal and to reset. Kabir hosts the Chart Detective duel
 * (doc 08 §2.2): his line sits here, outside the question component
 * — he never speaks during a question.
 *
 * The chart below is the real qb-571 chart, generated by the seeded
 * chart generator (STEADY_RISE, Meadow Foods): series
 * [92, 95, 97, 100, 105, 110], annotation rising 0–5.
 */

const SAMPLE_QUESTION: ChartQuestionView = {
  id: 'qb-571',
  stem: 'Look at the price chart of Meadow Foods, a fictional snack company, from January to June. What does the chart show?',
  options: [
    {
      id: 'qb-571-opt-0',
      text: 'The price rose steadily over the six months.',
      order: 0,
    },
    {
      id: 'qb-571-opt-1',
      text: 'The price fell steadily over the six months.',
      order: 1,
    },
    {
      id: 'qb-571-opt-2',
      text: 'The price stayed flat all six months.',
      order: 2,
    },
    {
      id: 'qb-571-opt-3',
      text: 'The price rose, then fell below where it started.',
      order: 3,
    },
  ],
  type: 'CHART_CHOICE',
  topic: 'money-basics',
  skill: 'CHART_READING',
  difficulty: 2,
  chart: {
    title: 'Meadow Foods — price over 6 months',
    instrument: 'Meadow Foods',
    template: 'STEADY_RISE',
    xLabel: 'Month',
    yLabel: 'Price (₹)',
    xLabels: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun'],
    series: [92, 95, 97, 100, 105, 110],
  },
};

const SAMPLE_REVEAL: ChartReveal = {
  correctOptionId: 'qb-571-opt-0',
  correctOptionText: 'The price rose steadily over the six months.',
  explanation:
    'Read the line from left to right: it climbs in almost every month and ends clearly higher than January. A line that keeps going up means the price rose.',
  annotation: { trend: 'rising', zoneStart: 0, zoneEnd: 5 },
};

export default function ChartFormatTestPage(): JSX.Element {
  const [reveal, setReveal] = useState<ChartReveal | null>(null);
  const [picked, setPicked] = useState<string | null>(null);
  const [round, setRound] = useState(0);

  function onAnswer(optionId: string): void {
    setPicked(optionId);
  }

  function showReveal(): void {
    if (!picked) return;
    setReveal({ ...SAMPLE_REVEAL, myOptionId: picked });
  }

  function reset(): void {
    setReveal(null);
    setPicked(null);
    setRound((r) => r + 1);
  }

  return (
    <main className="mx-auto max-w-2xl px-4 py-8">
      <h1 className="text-2xl font-bold">Chart format preview</h1>
      <p className="mt-2 text-sm text-slate-400">
        CHART_CHOICE format test page — not a duel. One seed chart (qb-571) rendered by the
        CHART_CHOICE renderer. Read the chart, pick the best interpretation, then reveal the correct
        reading with the trend annotation.
      </p>
      <p className="mt-3 rounded border border-slate-800 bg-slate-900/50 p-3 text-sm">
        <span className="font-medium text-amber-300">Kabir · </span>
        One chart, four readings. Read the line, not the noise — you have 30 seconds.
      </p>

      <div className="mt-6">
        <ChartQuestion
          key={`${SAMPLE_QUESTION.id}-${round}`}
          question={SAMPLE_QUESTION}
          reveal={reveal}
          onAnswer={onAnswer}
        />
      </div>

      {picked && !reveal && (
        <div className="mt-4 rounded border border-slate-800 bg-slate-900/50 p-3 text-sm">
          <p>
            Answer recorded: <span className="font-medium">{picked}</span>
          </p>
          <p className="mt-1 text-slate-400">
            A wrong chart read is a wrong answer — there is no partial credit for charts.
          </p>
          <button
            onClick={showReveal}
            className="mt-3 rounded bg-amber-400 px-5 py-2 font-medium text-slate-950 hover:bg-amber-300"
          >
            Reveal the correct reading
          </button>
        </div>
      )}

      {reveal && (
        <button
          onClick={reset}
          className="mt-4 rounded border border-slate-700 px-5 py-2 text-sm text-slate-300 hover:bg-slate-800"
        >
          Try the chart again
        </button>
      )}

      <Link href="/duels" className="mt-4 inline-block text-sm text-slate-400 underline">
        Back to duels
      </Link>
      <DuelsDisclaimer />
    </main>
  );
}
